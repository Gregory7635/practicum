package com.logistics.delivery.dto;

/**
 * Одна выявленная проблемная точка в отзыве клиента.
 * category — категория проблемы (например: "задержка", "повреждение упаковки",
 * "грубость курьера", "неверный адрес", "прочее").
 * severity — оценка серьёзности проблемы: LOW, MEDIUM, HIGH.
 *
 * Это DTO (Data Transfer Object) — объект, который используется только для
 * передачи данных наружу через REST API (в JSON-ответе). Он намеренно не
 * содержит никакой логики, только данные.
 */
public record ProblemPointDto(
        String category,     // категория проблемы строкой (значения задаёт LLM в промпте)
        String description,  // краткое текстовое описание конкретной проблемы
        String severity      // серьёзность: "LOW", "MEDIUM" или "HIGH"
) {
}
