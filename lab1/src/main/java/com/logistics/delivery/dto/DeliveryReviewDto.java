package com.logistics.delivery.dto;

/**
 * Входные данные: отзыв клиента о доставке.
 * orderId — идентификатор заказа, reviewText — текст отзыва клиента.
 *
 * Это Java record — компактный способ описать неизменяемый (immutable)
 * объект-данные без ручного написания конструктора, геттеров, equals/hashCode:
 * компилятор генерирует их автоматически на основе списка полей ниже.
 */
public record DeliveryReviewDto(
        String orderId,       // идентификатор заказа, к которому относится отзыв (обязателен)
        String reviewText,    // сам текст отзыва клиента на естественном языке (обязателен)
        Integer rating        // оценка клиента от 1 до 5; тип Integer (не int), чтобы поле могло быть null
) {
}
